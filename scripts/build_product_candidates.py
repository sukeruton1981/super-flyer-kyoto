#!/usr/bin/env python3
"""Create non-authoritative spatial candidate groups from positional OCR lines.

Run from repository root: python scripts/build_product_candidates.py
Reads data/flyer_ocr_review.json (generated by scan_flyer_layout.py).
Writes data/product_candidates_review.json and product_candidates_review.html.
NEVER writes verified_offers.json or price_history.json.
"""
import json
from datetime import datetime, timezone, timedelta
from html import escape
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'data' / 'flyer_ocr_review.json'
OUTPUT = ROOT / 'data' / 'product_candidates_review.json'
HTML = ROOT / 'product_candidates_review.html'
JST = timezone(timedelta(hours=9))


def near(a, b):
    """Heuristic grouping only: neighboring OCR *lines*, not product recognition."""
    x1, y1, w1, h1 = (a['box'][k] for k in ('left','top','width','height'))
    x2, y2, w2, h2 = (b['box'][k] for k in ('left','top','width','height'))
    overlap = max(0, min(x1+w1, x2+w2)-max(x1,x2))
    gap_y = max(0, max(y1,y2)-min(y1+h1,y2+h2))
    gap_x = max(0, max(x1,x2)-min(x1+w1,x2+w2))
    return (overlap > 0 and gap_y <= max(40, h1, h2)*1.6) or (gap_x < 40 and gap_y < 35)


def components(lines):
    """Grid buckets avoid quadratic comparison on large OCR sheets."""
    cell = 240
    parent = list(range(len(lines)))
    def root(i):
        while parent[i] != i:
            parent[i] = parent[parent[i]]
            i = parent[i]
        return i
    def union(i,j):
        a,b = root(i),root(j)
        if a != b: parent[b] = a
    buckets = {}
    for i, item in enumerate(lines):
        box=item['box']; cx=box['left']//cell; cy=box['top']//cell
        for xx in range(cx-2,cx+3):
            for yy in range(cy-2,cy+3):
                for j in buckets.get((xx,yy),[]):
                    if near(item, lines[j]): union(i,j)
        buckets.setdefault((cx,cy),[]).append(i)
    groups = {}
    for i,item in enumerate(lines):
        groups.setdefault(root(i),[]).append(item)
    return list(groups.values())


def main():
    raw=json.loads(SOURCE.read_text(encoding='utf-8'))
    report={'generated_at_jst': datetime.now(JST).isoformat(timespec='seconds'),
            'stage':'SPATIAL_CANDIDATES_UNVERIFIED','verified_products':0,
            'published_offers':0,'limitations':'Only candidate lines with numbers have bounding boxes. This cannot reliably associate product names, tax or validity dates.',
            'flyers':[]}
    for flyer in raw.get('items',[]):
        review={'shop':flyer.get('label','不明'), 'source_url':flyer.get('image_url'),
                'status':flyer.get('status'), 'groups':[]}
        lines=[x for x in flyer.get('price_like_lines',[]) if isinstance(x.get('box'),dict) and all(isinstance(x['box'].get(k),int) for k in ('left','top','width','height'))]
        for group in components(lines):
            xs=[x['box']['left'] for x in group]; ys=[x['box']['top'] for x in group]
            ex=[x['box']['left']+x['box']['width'] for x in group]
            ey=[x['box']['top']+x['box']['height'] for x in group]
            review['groups'].append({'box':{'left':min(xs),'top':min(ys),'width':max(ex)-min(xs),'height':max(ey)-min(ys)},
                                     'unverified_lines':[{'text':x.get('text',''), 'numbers':x.get('numbers',[]), 'confidence':x.get('average_ocr_confidence')} for x in group],
                                     'requires_human_review':True,'is_verified_product':False})
        review['groups'].sort(key=lambda x:(x['box']['top'],x['box']['left']))
        report['flyers'].append(review)
    OUTPUT.parent.mkdir(parents=True,exist_ok=True)
    OUTPUT.write_text(json.dumps(report,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
    cards=[]
    for flyer in report['flyers']:
        sections=[]
        for i,g in enumerate(flyer['groups'],1):
            rows=' / '.join(escape(x['text']) for x in g['unverified_lines'])
            loc=g['box']; sections.append(f'<li><b>候補 {i}</b> ({loc["left"]}, {loc["top"]})：{rows}</li>')
        link=flyer.get('source_url')
        anchor=f'<a href="{escape(link,quote=True)}" target="_blank" rel="noopener noreferrer">元画像</a>' if link else ''
        cards.append(f'<section><h2>{escape(flyer["shop"])}</h2><p>{anchor} / {len(flyer["groups"])} 組（未確認）</p><ol>{"".join(sections)}</ol></section>')
    page='''<!doctype html><html lang="ja"><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><title>商品候補の位置別確認</title><style>body{font-family:system-ui,sans-serif;max-width:960px;margin:auto;padding:18px;background:#f6f7fa;color:#16212b}section{background:white;border:1px solid #ddd;padding:16px;margin:15px 0;border-radius:12px}li{margin:12px 0;overflow-wrap:anywhere}a{color:#12549d}</style><h1>位置別OCR候補</h1><p><strong>注意：</strong>近接する数字入り行をまとめた試作です。商品名・価格・有効期間の組み合わせは未検証であり、価格比較には使用しません。</p>'''+''.join(cards)+'</html>'
    HTML.write_text(page,encoding='utf-8')
    print('Candidate groups:',sum(len(x['groups']) for x in report['flyers']),'published:',report['published_offers'])

if __name__=='__main__': main()
